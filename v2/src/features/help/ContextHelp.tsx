const normalize = (value: string | null | undefined) => String(value || '').trim().replace(/\s+/g, ' ').toUpperCase()

function activeText(selector: string) {
  return normalize(document.querySelector<HTMLElement>(selector)?.textContent)
}

function resolveTopicKey() {
  const section = activeText('.topbar__nav .chip--active') || 'ПОРТФЕЛЬ'

  if (section === 'ПОРТФЕЛЬ') {
    const view = activeText('.portfolio-workspace .subnav .subnav--active') || 'ОБЗОР'
    if (view === 'СТРУКТУРА') {
      const structureMode = activeText('.structure-switch .is-active') || 'КЛАССЫ'
      return `ПОРТФЕЛЬ|СТРУКТУРА|${structureMode}`
    }
    return `ПОРТФЕЛЬ|${view}`
  }

  if (section === 'АНАЛИТИКА') {
    const view = activeText('.analytics-subnav .subnav--active') || 'ОБЗОР'
    if (view === 'РИСК') {
      const riskMode = activeText('.risk-modebar button.is-active')
      return riskMode ? `АНАЛИТИКА|РИСК|${riskMode}` : 'АНАЛИТИКА|РИСК'
    }
    return `АНАЛИТИКА|${view}`
  }

  if (section === 'ДОХОД') {
    const view = activeText('.income-subnav button.is-active') || 'ОБЗОР'
    return `ДОХОД|${view}`
  }

  if (section === 'DNA') return 'DNA'
  return section
}

export function ContextHelp() {
  const [topicKey, setTopicKey] = useState('ПОРТФЕЛЬ|ОБЗОР')
  const detailsRef = useRef<HTMLDetailsElement>(null)

  useEffect(() => {
    let frame = 0
    const sync = () => {
      frame = 0
      setTopicKey(resolveTopicKey())
    }
    const scheduleSync = () => {
      if (frame) window.cancelAnimationFrame(frame)
      frame = window.requestAnimationFrame(sync)
    }
    const handleClick = (event: MouseEvent) => {
      const details = detailsRef.current
      if (details?.open && event.target instanceof Node && !details.contains(event.target)) details.open = false
      scheduleSync()
    }
    const handleKey = (event: KeyboardEvent) => {
      if (event.key === 'Escape' && detailsRef.current?.open) detailsRef.current.open = false
    }

    scheduleSync()
    document.addEventListener('click', handleClick, true)
    document.addEventListener('keydown', handleKey)
    return () => {
      if (frame) window.cancelAnimationFrame(frame)
      document.removeEventListener('click', handleClick, true)
      document.removeEventListener('keydown', handleKey)
    }
  }, [])

  const currentTopic = TOPICS[topicKey] ?? TOPICS[topicKey.split('|')[0]] ?? TOPICS.ПОРТФЕЛЬ

  return (
    <details className="context-help" ref={detailsRef} key={topicKey}>
      <summary aria-label={`Подсказка: ${currentTopic.title}`} title="Что здесь находится?">?</summary>
      <div className="context-help__card" role="note">
        <div className="context-help__head"><span>ЧТО ЗДЕСЬ?</span><strong>{currentTopic.title}</strong></div>
        <p>{currentTopic.intro}</p>
        <dl>
          {currentTopic.items.map(([term, description]) => (
            <div key={term}><dt>{term}</dt><dd>{description}</dd></div>
          ))}
        </dl>
        {currentTopic.note && <small>{currentTopic.note}</small>}
      </div>
    </details>
  )
}
